import { App } from "@modelcontextprotocol/ext-apps";
interface Decision {kind:"permit"|"permit-with-conditions"|"escalate"|"deny";reasonCodes:string[]}
interface Attempt {action:string;risk:string;status:"simulated"|"denied"|"escalated";decision:Decision}
interface Report {
 scenario:string;mode:string;managedEntityId:string;
 before:Record<string,number>;after:Record<string,number>;
 account:{fundedMinor:string;spentMinor:string;availableMinor:string};
 obligations:{obligationId:string;status:string;observedValue?:number}[];
 attemptedActions:Attempt[];
 events:{detail:string}[];
}
const app=new App({name:"AWC Operating Mandate Testbench",version:"0.1.0"});
const buttons=Array.from(document.querySelectorAll<HTMLButtonElement>("button[data-scenario]"));
const results=document.querySelector<HTMLDivElement>("#results")!;
const status=document.querySelector<HTMLParagraphElement>("#status")!;
const el=(tag:string,className?:string,text?:string)=>{
 const x=document.createElement(tag);
 if(className)x.className=className;
 if(text!==undefined)x.textContent=text;
 return x;
};
const money=(minor:string)=>new Intl.NumberFormat("en-US",{style:"currency",currency:"USD"}).format(Number(minor)/100);
function section(title:string){const card=el("section","card");card.append(el("h2",undefined,title));return card;}
function resultBox(data:Report){
 results.replaceChildren();
 status.textContent=data.scenario+" example complete — synthetic decisions only.";
 for(const b of buttons)b.dataset.active=String(b.dataset.scenario===data.scenario);
 const summary=section("Operational state");
 summary.append(el("p",undefined,"Managed entity: "+data.managedEntityId));
 const grid=el("div","grid");
 const values=[
  ["Funded account",money(data.account.fundedMinor)],
  ["Simulated committed expense",money(data.account.spentMinor)],
  ["Available balance",money(data.account.availableMinor)],
 ];
 for(const [label,value] of values){const metric=el("div","metric");metric.append(
  el("div","muted",label),el("strong",undefined,value));grid.append(metric);}
 summary.append(grid);
 const funded=Number(data.account.fundedMinor),spent=Number(data.account.spentMinor);
 const track=el("div","track");
 const used=el("span");used.style.width=(funded?Math.max(0,Math.min(100,spent/funded*100)):0)+"%";
 const remaining=el("span","funded");remaining.style.width=(funded?Math.max(0,Math.min(100,100-spent/funded*100)):0)+"%";
 track.append(used,remaining);summary.append(track);results.append(summary);

 const actions=section("Delegated actions");
 const list=el("div","rows");
 for(const a of data.attemptedActions){
  const row=el("div","row");const text=el("div");
  text.append(el("strong",undefined,a.action),el("p",undefined,
   a.decision.reasonCodes.length?a.decision.reasonCodes.join(" · "):"Policy check passed"));
  const tag=el("span","tag "+a.status,a.status);
  row.append(text,tag);list.append(row);
 }actions.append(list);results.append(actions);

 const objectives=section("Obligation assessment");
 const rows=el("div","rows");
 for(const o of data.obligations){
  const row=el("div","row");
  row.append(el("span",undefined,o.obligationId+
   (o.observedValue===undefined?"":" · observed "+o.observedValue)),
   el("span","tag "+(o.status==="met"?"met":o.status==="breached"?"breached":"unknown"),o.status));
  rows.append(row);
 }objectives.append(rows);results.append(objectives);

 const provenance=section("Simulation evidence");
 provenance.append(el("p",undefined,data.events.length+" signed-format-compatible event references generated by a synthetic actor. These are NOT Attest credentials or independently verified events."));
 results.append(provenance);
}
app.ontoolresult=value=>{
 const data=value.structuredContent as Report|undefined;
 if(data?.mode==="strictly-simulated"&&Array.isArray(data.attemptedActions))resultBox(data);
};
for(const button of buttons)button.addEventListener("click",async()=>{
 const scenario=button.dataset.scenario;
 if(!scenario||!["vending","cloud","plant"].includes(scenario))return;
 buttons.forEach(x=>x.disabled=true);status.textContent="Evaluating the fictional mandate...";
 try{
  const response=await app.callServerTool({name:"operations.simulate",arguments:{scenario}});
  const data=response.structuredContent as Report|undefined;
  if(data?.mode==="strictly-simulated")resultBox(data);
  else status.textContent="Simulation returned no structured results.";
 }catch{
  status.textContent="Connect this App to an MCP Apps-compatible host to run simulations.";
 }finally{buttons.forEach(x=>x.disabled=false);}
});
void app.connect().catch(()=>{status.textContent="This demonstration requires an MCP Apps-compatible host.";});
